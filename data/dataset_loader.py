class CEDatasetFromIndices:
    """
    Load and reconstruct CE datasets from index files.

    This class reads index files generated by ce_generator.py and reconstructs
    the full CE dataset by loading raw sensor data from the multimodal dataset
    files.

    Note: This class generates base (non-shifted) datasets.
    """

    def __init__(self, duration, split, n_samples=None, rule_only=False, multimodal_base_path='./Multimodal/', index_file_dir='./CE_dataset/'):
        """
        Initialize the dataset loader.

        Args:
            duration: Time window duration (5, 15, or 30 minutes)
            split: Dataset split ('train', 'val', or 'test')
            n_samples: Number of samples (required for train split)
            rule_only: If True, load rule-only test set (only valid for test split)
            multimodal_base_path: Directory containing multimodal dataset files
                                 (default: './Multimodal/')
            index_file_dir: Directory containing index files (default: './CE_dataset/')
        """
        # Validate arguments
        if split == 'train' and n_samples is None:
            raise ValueError("n_samples is required for train split")
        if rule_only and split != 'test':
            raise ValueError("rule_only can only be used with test split")

        # Construct index filename: ce5min_train_indices_2000.npz, ce5min_test_rule_indices.npz
        class_name = f"ce{duration}min"
        suffix = "_rule" if rule_only else ""
        if split == 'train':
            filename = f"{class_name}_{split}{suffix}_indices_{n_samples}.npz"
        else:
            filename = f"{class_name}_{split}{suffix}_indices.npz"

        self.index_file = str(Path(index_file_dir) / filename)
        self.multimodal_path = Path(multimodal_base_path)

        print(f"Loading index file: {self.index_file}")
        self.index_data = np.load(self.index_file, allow_pickle=True)

        # Parse config
        self.config = json.loads(str(self.index_data['config']))
        print(f"  Config: {self.config['time_window_class']}, "
              f"{self.config['n_data']} samples, "
              f"{self.config['data_cat']} split")

        # Load raw multimodal data
        self._load_multimodal_data()

        print(f"✓ Dataset loader initialized")
        print(f"  {len(self.index_data['sensor_data_indices'])} CE samples ready")

    def _load_multimodal_data(self):
        """Load raw sensor data from multimodal dataset files using memory-mapped mode for efficiency."""
        # Only load the files actually needed based on data category
        data_cat = self.config['data_cat']

        train_path = self.multimodal_path / 'MultimodalDataset_audio-40000_1234_imu-50_1234.npz'
        test_path = self.multimodal_path / 'MultimodalDataset_audio-40000_5_imu-50_5.npz'

        if data_cat == 'train':
            # Only need train data (subjects 1-4)
            print(f"  Opening: {train_path.name} (subjects 1-4)")
            self.train_data = np.load(train_path, mmap_mode='r')
            self.test_data = None
        else:
            # Only need test data (subject 5)
            print(f"  Opening: {test_path.name} (subject 5)")
            self.train_data = None
            self.test_data = np.load(test_path, mmap_mode='r')

    def generate_sample(self, sample_idx):
        """
        Reconstruct one CE sample from indices.

        Args:
            sample_idx: Which CE sample to generate (0 to n_samples-1)

        Returns:
            tuple of (sounds, imus, ce_label, actions, action_labels)
                - sounds: (n_windows, 1, audio_samples) - Audio data
                - imus: (n_windows, 6, imu_samples) - IMU data
                - ce_label: (n_windows,) - Complex event labels
                - actions: (n_windows,) - Action names
                - action_labels: (n_windows,) - Action label IDs

        Note: Temporal shifts should be applied to the entire saved CE dataset,
              not during sample reconstruction. Use dataset_loader.py CLI for shifts.
        """
        # Get indices and metadata for this sample
        indices = self.index_data['sensor_data_indices'][sample_idx]
        data_source = str(self.index_data['data_sources'][sample_idx])
        ce_label = self.index_data['ce_labels'][sample_idx]
        actions = self.index_data['actions'][sample_idx]
        action_labels = self.index_data['action_labels'][sample_idx]

        # Select appropriate dataset
        dataset = self.train_data if data_source == 'train' else self.test_data

        # Convert indices to integer array for fancy indexing (much faster than individual copies!)
        indices = np.array(indices, dtype=np.int64)
        sounds = dataset['sounds'][indices]  # Shape: (n_windows, 1, audio_samples)
        imus = dataset['imus'][indices]      # Shape: (n_windows, 6, imu_samples)

        return sounds, imus, ce_label, actions, action_labels

    def generate_full_dataset(self, show_progress=True):
        """
        Generate entire CE dataset from indices using efficient vectorized operations.

        Args:
            show_progress: Whether to show progress bar

        Returns:
            tuple of (sounds, imus, ce_labels, actions, action_labels)

        Note: This generates the base (non-shifted) dataset. For temporal shifts,
              save this dataset first, then use dataset_loader.py CLI.
        """
        # Determine which data source to use based on what's loaded
        if self.train_data is not None:
            source_data = self.train_data
            source_name = "train data (subjects 1-4)"
        else:
            source_data = self.test_data
            source_name = "test data (subject 5)"

        # Get all indices for this dataset
        all_indices = self.index_data['sensor_data_indices']
        n_samples = len(all_indices)
        n_windows = len(all_indices[0])  # All samples have same n_windows

        # Get array shapes from metadata (no data loading)
        audio_samples = source_data['sounds'].shape[2]
        imu_samples = source_data['imus'].shape[2]
        dtype_sounds = source_data['sounds'].dtype
        dtype_imus = source_data['imus'].dtype

        if show_progress:
            print(f"\nLoading {n_samples} samples from {source_name}...")

        # Pre-allocate output arrays for efficient memory usage
        all_sounds = np.empty((n_samples, n_windows, 1, audio_samples), dtype=dtype_sounds)
        all_imus = np.empty((n_samples, n_windows, 6, imu_samples), dtype=dtype_imus)

        # Load data sample-by-sample for better disk access patterns
        # Loading per-sample is faster than one giant fancy index due to better locality
        iterator = tqdm(enumerate(all_indices), total=n_samples, desc="  Loading") if show_progress else enumerate(all_indices)

        for i, indices in iterator:
            # Convert to numpy array once
            idx_array = np.asarray(indices, dtype=np.int64)

            # Load directly into pre-allocated arrays (no intermediate copies)
            all_sounds[i] = source_data['sounds'][idx_array]
            all_imus[i] = source_data['imus'][idx_array]

        if show_progress:
            print(f"  ✓ Loaded {n_samples} samples")

        # Labels and actions (no need to reconstruct, already in index file)
        all_ce_labels = self.index_data['ce_labels']
        all_actions = self.index_data['actions']
        all_action_labels = self.index_data['action_labels']

        return all_sounds, all_imus, all_ce_labels, all_actions, all_action_labels

    def load_batch(self, start_idx, end_idx, show_progress=False):
        """
        Load a batch of samples (memory-efficient version of generate_full_dataset).

        Args:
            start_idx: Starting sample index (inclusive)
            end_idx: Ending sample index (exclusive)
            show_progress: Whether to show progress bar

        Returns:
            tuple of (sounds, imus)
        """
        # Determine which data source to use
        if self.train_data is not None:
            source_data = self.train_data
        else:
            source_data = self.test_data

        # Get indices for batch
        all_indices = self.index_data['sensor_data_indices']
        batch_indices = all_indices[start_idx:end_idx]
        n_samples = len(batch_indices)
        n_windows = len(batch_indices[0])

        # Get array shapes
        audio_samples = source_data['sounds'].shape[2]
        imu_samples = source_data['imus'].shape[2]
        dtype_sounds = source_data['sounds'].dtype
        dtype_imus = source_data['imus'].dtype

        # Vectorized loading: concatenate all indices and load at once
        if show_progress:
            print(f"    Loading batch...")

        # Flatten all indices for this batch
        all_flat_indices = np.concatenate([np.asarray(idx, dtype=np.int64) for idx in batch_indices])

        # Single batch load from mmap
        batch_sounds_flat = source_data['sounds'][all_flat_indices]
        batch_imus_flat = source_data['imus'][all_flat_indices]

        # Reshape back to (n_samples, n_windows, ...)
        batch_sounds = batch_sounds_flat.reshape(n_samples, n_windows, 1, audio_samples)
        batch_imus = batch_imus_flat.reshape(n_samples, n_windows, 6, imu_samples)

        return batch_sounds, batch_imus

    def get_info(self):
        """Get information about the dataset."""
        n_samples = len(self.index_data['sensor_data_indices'])
        avg_windows = np.mean([len(idx) for idx in self.index_data['sensor_data_indices']])

        info = {
            'n_samples': n_samples,
            'avg_windows_per_sample': avg_windows,
            'config': self.config,
        }

        return info


