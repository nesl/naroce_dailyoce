def generate_ae2ce_from_fusion(fusion_embeddings, ae_classifier, device='cuda', soft=False, batch_size=512):
    """
    Generate AE2CE embeddings on-the-fly from fusion embeddings.

    Passes fusion embeddings through the AE classifier to get atomic activity predictions.
    This is fast enough to run on-the-fly without caching.

    Args:
        fusion_embeddings: Fusion embeddings of shape (N, 128)
        ae_classifier: Trained AE classifier model
        device: Device for computation ('cuda' or 'cpu')
        soft: If True, return soft probabilities; if False, return one-hot predictions
        batch_size: Batch size for inference (default: 512)

    Returns:
        ae2ce_embeddings: AE predictions of shape (N, 9)
                         One-hot encoded if soft=False, probabilities if soft=True
    """
    import torch

    ae_classifier.eval()
    ae_classifier.to(device)

    n_windows = fusion_embeddings.shape[0]
    print(f"  Generating {'soft-' if soft else ''}AE2CE embeddings from fusion...")
    print(f"  Processing {n_windows} windows, 128-dim → 9-dim")
    print(f"  Batch size: {batch_size}")

    # Pre-allocate output array
    ae2ce_embeddings = np.zeros((n_windows, 9), dtype=np.float32)

    # Convert to tensor
    embeddings_tensor = torch.from_numpy(fusion_embeddings).to(device)

    # Process in batches
    with torch.no_grad():
        for i in tqdm(range(0, n_windows, batch_size), desc="  Classifying"):
            batch = embeddings_tensor[i:i+batch_size]

            # Run classifier: (batch, 128) → (batch, 9)
            # Classifier already applies softmax in forward pass
            logits = ae_classifier(batch)

            if soft:
                # Keep soft probabilities
                ae2ce_embeddings[i:i+batch_size] = logits.cpu().numpy()
            else:
                # Convert to one-hot
                _, preds = logits.topk(1, dim=1)  # (batch, 1)
                preds_one_hot = torch.nn.functional.one_hot(preds.squeeze(-1), num_classes=9)  # (batch, 9)
                ae2ce_embeddings[i:i+batch_size] = preds_one_hot.cpu().numpy().astype(np.float32)

    print(f"  ✓ AE2CE embeddings generated: {ae2ce_embeddings.shape}")
    return ae2ce_embeddings


