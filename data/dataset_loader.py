def generate_embeddings(sounds, imus, audio_model=None, imu_model=None, fusion_model=None, device=None, batch_size=128):
    """
    Generate fused embeddings from raw sensor data using three-stage pipeline:
    1. BEATs: audio → 768-dim embeddings (per timestep)
    2. LIMUBert: IMU → 72-dim embeddings (per timestep)
    3. Fusion model: (audio_emb, imu_emb) → 128-dim fused embedding

    Uses efficient batching to process multiple windows at once.

    Args:
        sounds: Audio array of shape (n_samples, n_windows, 1, 40000)
        imus: IMU array of shape (n_samples, n_windows, 6, 50)
        audio_model: BEATs model (optional, loaded if None)
        imu_model: LIMUBert model (optional, loaded if None)
        fusion_model: Multimodal fusion model (optional, loaded if None)
        device: Device for computation (auto-detected if None)
        batch_size: Number of windows to process at once (default: 128)

    Returns:
        embeddings: Fused embeddings of shape (n_samples, n_windows, 128)
    """
    import torch

    # Auto-detect device
    if device is None:
        device = 'cuda' if torch.cuda.is_available() else 'cpu'

    print(f"\n  Using device: {device}")

    # Load models if not provided
    if audio_model is None:
        audio_model = load_beats_model(device)
    if imu_model is None:
        imu_model = load_limubert_model(device)
    if fusion_model is None:
        fusion_model = load_multimodal_fusion_model(device)

    n_samples, n_windows = sounds.shape[:2]

    print(f"  Generating embeddings for {n_samples} samples, {n_windows} windows each...")
    print(f"  Audio: {sounds.shape[3]} samples/window, IMU: {imus.shape[3]} samples/window")
    print(f"  Pipeline: BEATs (768-dim) + LIMUBert (72-dim) → Fusion (128-dim)")
    print(f"  Batch size: {batch_size} windows")

    # Reshape for batching: (n_samples, n_windows, ...) -> (n_samples * n_windows, ...)
    # Use torch.from_numpy for zero-copy conversion, then make contiguous for faster GPU transfer
    sounds_tensor = torch.from_numpy(sounds.reshape(-1, sounds.shape[2], sounds.shape[3])).contiguous()
    imus_tensor = torch.from_numpy(imus.reshape(-1, imus.shape[2], imus.shape[3])).contiguous()

    # Create dataset and dataloader with pin_memory for faster CPU→GPU transfer
    dataset = TensorDataset(sounds_tensor, imus_tensor)
    dataloader = DataLoader(dataset, batch_size=batch_size, shuffle=False, num_workers=0, pin_memory=True)

    # Single-pass pipeline: Audio → IMU → Fusion (all in one loop)
    print("  Generating embeddings (BEATs → LIMUBert → Fusion)...")
    fused_embeddings_list = []

    with torch.no_grad():
        for batch_sounds, batch_imus in tqdm(dataloader, desc="  Processing"):
            # Stage 1: BEATs audio embeddings
            # BEATs expects (batch, audio_samples), squeeze out channel dimension
            batch_sounds = batch_sounds[:, 0, :].to(device, non_blocking=True)  # (batch, 40000)
            padding_mask = torch.zeros_like(batch_sounds, dtype=torch.bool)
            audio_embeds = audio_model.extract_features(batch_sounds, padding_mask=padding_mask)[0]
            # (batch, timesteps, 768)

            # Stage 2: LIMUBert IMU embeddings
            # (batch, imu_channels, imu_samples) -> (batch, imu_samples, imu_channels) for LIMUBert
            batch_imus = batch_imus.permute(0, 2, 1).to(device, non_blocking=True)
            imu_embeds = imu_model(batch_imus)  # (batch, imu_samples, 72)

            # Stage 3: Fusion
            # (batch, audio_timesteps, 768) + (batch, imu_timesteps, 72) -> (batch, 128)
            fused = fusion_model.extract_features(audio_embeds, imu_embeds)
            fused_embeddings_list.append(fused)

    # Concatenate all batches and move to CPU
    fused_embeddings = torch.cat(fused_embeddings_list, dim=0).cpu().numpy()

    # Free memory
    del fused_embeddings_list

    # Reshape back to (n_samples, n_windows, 128)
    embeddings = fused_embeddings.reshape(n_samples, n_windows, 128)

    return embeddings


def apply_temporal_shift_to_raw_data(sounds, imus, temporal_shift):
    """
    Apply temporal shift to raw sensor data (before embedding).

    Shifts the ENTIRE continuous sensor trace for each CE sample,
    allowing data to flow between windows. Uses circular shift (wrap around).

    Args:
        sounds: Audio array of shape (n_samples, n_windows, 1, 40000)
        imus: IMU array of shape (n_samples, n_windows, 6, 50)
        temporal_shift: Shift as fraction of window length (e.g., 0.1 = 10% of window)

    Returns:
        shifted_sounds: Shifted audio array of same shape
        shifted_imus: Shifted IMU array of same shape
    """
    # Convert fraction to absolute time using WINDOW_SIZE hyperparameter
    temporal_shift_sec = temporal_shift * WINDOW_SIZE

    print(f"\n  Applying temporal shift to raw sensor data...")
    print(f"  Window size: {WINDOW_SIZE}s")
    print(f"  Shift fraction: {temporal_shift} ({temporal_shift*100:.0f}% of window)")
    print(f"  Absolute shift: {temporal_shift_sec}s")
    print(f"  (Using circular shift - data wraps around)")

    # Audio shift parameters
    audio_sample_rate = 16000
    audio_shift_samples = int(temporal_shift_sec * audio_sample_rate)

    # IMU shift parameters
    imu_sample_rate = 20
    imu_shift_samples = int(temporal_shift_sec * imu_sample_rate)

    n_samples = sounds.shape[0]
    n_windows = sounds.shape[1]

    # === AUDIO: Vectorized shift (no Python loop) ===
    # Input: (n_samples, n_windows, 1, 40000)
    # Reshape to continuous: (n_samples, 1, n_windows * 40000)
    continuous_audio = sounds.reshape(n_samples, 1, -1)
    # Apply shift to all samples at once
    shifted_continuous_audio = np.roll(continuous_audio, audio_shift_samples, axis=2)
    # Reshape back to windows: (n_samples, n_windows, 1, 40000)
    shifted_sounds = shifted_continuous_audio.reshape(n_samples, n_windows, 1, -1)

    # === IMU: Vectorized shift (no Python loop) ===
    # Input: (n_samples, n_windows, 6, 50)
    # Reshape to continuous: (n_samples, 6, n_windows * 50)
    continuous_imu = imus.reshape(n_samples, 6, -1)
    # Apply shift to all samples at once
    shifted_continuous_imu = np.roll(continuous_imu, imu_shift_samples, axis=2)
    # Reshape back to windows: (n_samples, n_windows, 6, 50)
    shifted_imus = shifted_continuous_imu.reshape(n_samples, n_windows, 6, -1)

    print(f"  ✓ Shift applied to {n_samples} samples (vectorized)")

    return shifted_sounds, shifted_imus


def apply_adjacent_window_fusion(embeddings, fusion_factor):
    """
    Apply adjacent window fusion to embeddings (after generation).

    Fuses each window with a weighted portion of the previous window.
    Formula: fused[t] = (1 - α) * current[t] + α * previous[t-1]

    Args:
        embeddings: Embedding array of shape (n_samples, n_windows, embed_dim)
        fusion_factor: Fusion weight α (e.g., 0.1 = 10% previous + 90% current)

    Returns:
        fused_embeddings: Fused embedding array of same shape
    """
    print(f"\n  Applying adjacent window fusion to embeddings...")
    print(f"  Fusion factor: {fusion_factor} ({fusion_factor*100:.0f}% previous + {(1-fusion_factor)*100:.0f}% current)")

    n_samples, n_windows, embed_dim = embeddings.shape

    # Vectorized fusion: process all samples at once
    # Create a copy for output
    fused_embeddings = embeddings.copy()

    # For windows t=1 onwards, fuse with previous window
    # fused[t] = (1 - α) * current[t] + α * previous[t-1]
    if n_windows > 1:
        fused_embeddings[:, 1:, :] = (1 - fusion_factor) * embeddings[:, 1:, :] + \
                                       fusion_factor * embeddings[:, :-1, :]

    # First window (t=0) remains unchanged (no previous window)
    print(f"  ✓ Fusion applied to {n_samples} samples (vectorized)")

    return fused_embeddings


def load_cached_embeddings(dataset_path, audio_model=None, imu_model=None, fusion_model=None,
                           device=None, batch_size=32, force_recompute=False):
    """
    Load precomputed fusion embeddings or compute them if not available.

    This function checks for cached fusion embeddings and loads them if available.
    If not available, it computes embeddings for all windows in the raw dataset
    and saves them for future use.

    Args:
        dataset_path: Path to raw multimodal .npz file
                     (e.g., 'MultimodalDataset_audio-40000_1234_imu-50_1234.npz')
        audio_model: BEATs model (optional, loaded if None)
        imu_model: LIMUBert model (optional, loaded if None)
        fusion_model: Multimodal fusion model (optional, loaded if None)
        device: Device for computation (auto-detected if None)
        batch_size: Batch size for embedding generation (default: 32)
        force_recompute: If True, recompute embeddings even if cache exists

    Returns:
        embeddings: Precomputed fusion embeddings of shape (N, 128) where N is
                   the total number of windows in the raw dataset
    """
    import torch

    cache_dir = Path(CACHED_EMBEDDINGS_DIR)

    # Construct cache filename: fusion_audio-40000_1234_imu-50_1234_embeddings.npz
    # Strip "MultimodalDataset_" prefix from filename
    dataset_name = Path(dataset_path).stem  # Extract filename without extension
    if dataset_name.startswith('MultimodalDataset_'):
        dataset_name = dataset_name[len('MultimodalDataset_'):]
    cache_file = cache_dir / f"fusion_{dataset_name}_embeddings.npz"

    # Check if cached embeddings exist
    if cache_file.exists() and not force_recompute:
        print(f"  ✓ Loading cached embeddings from {cache_file.name}")
        cached_data = np.load(cache_file)
        embeddings = cached_data['embeddings']
        print(f"    Shape: {embeddings.shape}, Size: {cache_file.stat().st_size / (1024**2):.1f} MB")
        return embeddings

    # Cache doesn't exist - need to compute embeddings
    print(f"  Cache not found: {cache_file.name}")
    print(f"  Computing embeddings for all windows in {Path(dataset_path).name}...")
    print(f"  (This is a one-time operation - future runs will use cached embeddings)")

    # Auto-detect device
    if device is None:
        device = 'cuda' if torch.cuda.is_available() else 'cpu'

    # Load models if not provided
    if audio_model is None:
        audio_model = load_beats_model(device)
    if imu_model is None:
        imu_model = load_limubert_model(device)
    if fusion_model is None:
        fusion_model = load_multimodal_fusion_model(device)

    # Load raw data
    print(f"  Loading raw sensor data from {Path(dataset_path).name}...")
    data = np.load(dataset_path)
    sounds = data['sounds']  # (N, 1, 40000)
    imus = data['imus']      # (N, 6, 50)
    labels = data['labels'] if 'labels' in data else None

    print(f"    Sounds: {sounds.shape}, IMUs: {imus.shape}")

    # Add dummy n_samples dimension for compatibility with generate_embeddings()
    # (N, 1, 40000) -> (1, N, 1, 40000)
    sounds_batch = sounds[np.newaxis, :, :, :]
    imus_batch = imus[np.newaxis, :, :, :]

    # Generate embeddings
    print(f"  Generating fusion embeddings...")
    embeddings = generate_embeddings(sounds_batch, imus_batch, audio_model, imu_model,
                                    fusion_model, device, batch_size)

    # Remove dummy n_samples dimension: (1, N, 128) -> (N, 128)
    embeddings = embeddings.squeeze(0)

    # Save cache for future use
    print(f"  Saving cached embeddings to {cache_file.name}...")
    cache_dir.mkdir(parents=True, exist_ok=True)
    np.savez(cache_file, embeddings=embeddings, labels=labels if labels is not None else np.array([]))

    cache_size_mb = cache_file.stat().st_size / (1024**2)
    print(f"  ✓ Cached embeddings saved ({cache_size_mb:.1f} MB)")

    return embeddings


def generate_embeddings_from_cache(loader, cached_embeddings):
    """
    Generate CE embeddings by indexing into precomputed embeddings.

    This function is much faster than generate_embeddings() because it only
    performs array indexing instead of running BEATs + LIMUBert + Fusion models.

    Args:
        loader: CEDatasetFromIndices instance with index data
        cached_embeddings: Precomputed embeddings array (N, 128)

    Returns:
        embeddings: CE embeddings of shape (n_samples, n_windows, 128)
    """
    sensor_indices = loader.index_data['sensor_data_indices']
    n_samples = len(sensor_indices)
    n_windows = len(sensor_indices[0])

    print(f"  Extracting embeddings from cache using indices...")
    print(f"  Processing {n_samples} samples, {n_windows} windows each")

    # Vectorized approach: flatten all indices, single fancy indexing, then reshape
    # Convert to (n_samples, n_windows) array then flatten
    all_indices = np.array(sensor_indices, dtype=np.int64).ravel()

    # Single fancy indexing operation: (n_samples * n_windows, embed_dim)
    all_embeddings = cached_embeddings[all_indices]

    # Auto-detect embedding dimension (128 for fusion, 9 for ae2ce)
    embed_dim = cached_embeddings.shape[1]

    # Reshape to (n_samples, n_windows, embed_dim)
    embeddings = all_embeddings.reshape(n_samples, n_windows, embed_dim)

    return embeddings


