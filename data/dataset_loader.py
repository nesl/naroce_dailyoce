def load_beats_model(device='cuda'):
    """
    Load BEATs audio embedding model.

    Args:
        device: Device to load model on ('cuda' or 'cpu')

    Returns:
        model: BEATs model instance
    """
    import sys
    import torch

    print(f"  Loading BEATs audio model from {BEATS_MODEL_PATH}...")

    # Add BEATs to path
    sys.path.append('./saved_models/BEATs')
    from BEATs import BEATs, BEATsConfig

    # Load checkpoint
    checkpoint = torch.load(BEATS_MODEL_PATH, map_location=device)
    cfg = BEATsConfig(checkpoint['cfg'])
    model = BEATs(cfg)
    model.load_state_dict(checkpoint['model'])
    model.eval()
    model.to(device)

    print(f"  ✓ BEATs model loaded on {device}")
    return model


