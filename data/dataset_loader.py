def load_multimodal_fusion_model(device='cuda', model_path=None):
    """
    Load the multimodal fusion model that combines audio and IMU embeddings.

    Args:
        device: Device to load model on ('cuda' or 'cpu')
        model_path: Path to model file (optional, defaults to MULTIMODAL_MODEL_PATH)

    Returns:
        model: AudioAndIMUFusion model instance
    """
    import sys
    import torch
    from torch import nn

    if model_path is None:
        model_path = MULTIMODAL_MODEL_PATH

    print(f"  Loading multimodal fusion model from {model_path}...")

    # Define the GRU module (needed for AudioAndIMUFusion)
    class GRU(nn.Module):
        def __init__(self, input_feature_dim, output_feature_dim):
            super().__init__()
            self.dropout = True
            self.num_rnn = 2
            self.rnn_io = [[input_feature_dim, 256], [256, output_feature_dim]]
            self.num_layers = [2, 1]
            for i in range(self.num_rnn):
                self.__setattr__('gru' + str(i), nn.GRU(self.rnn_io[i][0], self.rnn_io[i][1],
                                                        num_layers=self.num_layers[i], batch_first=True))

        def forward(self, input_seqs, training=False):
            h = input_seqs
            for i in range(self.num_rnn):
                rnn = self.__getattr__('gru' + str(i))
                h, _ = rnn(h)
                h = nn.functional.relu(h)
            h = h[:, -1, :]
            if self.dropout:
                h = nn.functional.dropout(h, training=training)
            return h

    # Define the fusion model architecture
    class AudioAndIMUFusion(nn.Module):
        def __init__(self, audio_feature_dim1, imu_feature_dim1, audio_feature_dim2,
                     imu_feature_dim2, fusion_output_dim, output_dim, dropout_p=0.0):
            super().__init__()
            self.audio_fc = nn.Linear(in_features=audio_feature_dim1, out_features=audio_feature_dim2)
            self.imu_gru = GRU(imu_feature_dim1, imu_feature_dim2)
            self.audio_bn = nn.BatchNorm1d(audio_feature_dim2)
            self.imu_bn = nn.BatchNorm1d(imu_feature_dim2)
            self.fusion = nn.Linear(in_features=(audio_feature_dim2 + imu_feature_dim2),
                                   out_features=fusion_output_dim)
            self.fc = nn.Linear(in_features=fusion_output_dim, out_features=output_dim)
            self.dropout = nn.Dropout(dropout_p)

        def forward(self, audio_embeddings, imu_embeddings):
            audio_features = self.audio_fc(audio_embeddings.mean(dim=1))
            imu_features = self.imu_gru(imu_embeddings)
            audio_features = self.audio_bn(audio_features)
            imu_features = self.imu_bn(imu_features)
            combined = torch.cat([audio_features, imu_features], dim=1)
            fused = self.dropout(nn.functional.relu(self.fusion(combined)))
            logits = self.fc(fused)
            return logits

        def extract_features(self, audio_embeddings, imu_embeddings):
            audio_features = self.audio_fc(audio_embeddings.mean(dim=1))
            imu_features = self.imu_gru(imu_embeddings)
            audio_features = self.audio_bn(audio_features)
            imu_features = self.imu_bn(imu_features)
            combined = torch.cat([audio_features, imu_features], dim=1)
            fused = nn.functional.relu(self.fusion(combined))
            return fused

    # Load checkpoint
    checkpoint = torch.load(model_path, map_location=device)

    # Instantiate model with config from checkpoint
    model = AudioAndIMUFusion(
        checkpoint['model_config']['audio_feature_dim1'],
        checkpoint['model_config']['imu_feature_dim1'],
        checkpoint['model_config']['audio_feature_dim2'],
        checkpoint['model_config']['imu_feature_dim2'],
        checkpoint['model_config']['fusion_output_dim'],
        checkpoint['model_config']['n_class'],
        dropout_p=0.0
    )

    model.load_state_dict(checkpoint['model_state_dict'])
    model.eval()
    model.to(device)

    print(f"  ✓ Multimodal fusion model loaded on {device}")
    return model


def load_ae_classifier(device='cuda', model_path=None):
    """
    Load the AE (Atomic Event) classifier.

    This classifier maps 128-dim fusion embeddings to 9 atomic activity classes.

    Args:
        device: Device to load model on ('cuda' or 'cpu')
        model_path: Path to model file (optional, defaults to AE_CLASSIFIER_PATH)

    Returns:
        model: FusionClassifier model instance
    """
    import torch
    from torch import nn

    if model_path is None:
        model_path = AE_CLASSIFIER_PATH

    print(f"  Loading AE classifier from {model_path}...")

    # Define the FusionClassifier architecture
    class FusionClassifier(nn.Module):
        def __init__(self, fusion_dim, output_dim, dropout_p=0.0):
            super().__init__()
            self.fc = nn.Linear(in_features=fusion_dim, out_features=output_dim)
            self.dropout = nn.Dropout(dropout_p)

        def forward(self, fusion_embeddings):
            logits = self.fc(fusion_embeddings)
            logits = torch.softmax(logits, dim=1)
            return logits

    # Create model instance (128-dim → 9 classes)
    model = FusionClassifier(fusion_dim=128, output_dim=9, dropout_p=0.0)

    # Load trained weights
    model.load_state_dict(torch.load(model_path, map_location=device))
    model.eval()
    model.to(device)

    print(f"  ✓ AE classifier loaded on {device}")
    return model


def embed_audio_window(model, audio, device='cuda'):
    """
    Generate embedding for a single audio window using BEATs.
    Note: This function is not used in the main pipeline but kept for reference.

    Args:
        model: BEATs model
        audio: Audio array of shape (channels, audio_samples)
        device: Device for computation

    Returns:
        embedding: Audio embedding sequence of shape (timesteps, 768)
                  where timesteps depends on audio_samples
    """
    import torch

    # Convert to tensor and add batch dimension
    audio_tensor = torch.from_numpy(audio).unsqueeze(0).to(device)
    padding_mask = torch.zeros_like(audio_tensor).bool()

    with torch.no_grad():
        # Extract features: (1, timesteps, 768)
        features = model.extract_features(audio_tensor, padding_mask=padding_mask)[0]

    return features.squeeze(0).cpu().numpy().astype(np.float32)  # (timesteps, 768)


def embed_imu_window(model, imu, device='cuda'):
    """
    Generate embedding for a single IMU window using LIMUBert.
    Note: This function is not used in the main pipeline but kept for reference.

    Args:
        model: LIMUBert model
        imu: IMU array of shape (channels, imu_samples)
        device: Device for computation

    Returns:
        embedding: IMU embedding sequence of shape (imu_samples, 72)
    """
    import torch

    # Convert to tensor: (channels, imu_samples) -> (1, imu_samples, channels) for LIMUBert
    imu_tensor = torch.from_numpy(imu).unsqueeze(0).permute(0, 2, 1).to(device)

    with torch.no_grad():
        # Extract features: (1, imu_samples, 72)
        features = model(imu_tensor)

    return features.squeeze(0).cpu().numpy().astype(np.float32)  # (imu_samples, 72)


